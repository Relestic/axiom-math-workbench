"""Reviewed visualization templates (scenes use the frontend camelCase contract)."""

from __future__ import annotations


def _curve(
    expression: str,
    label: str,
    *,
    curve_id: str = "f",
    domain_min: float | None = None,
    domain_max: float | None = None,
    left_open: bool = False,
    right_open: bool = False,
    visible: bool = True,
) -> dict:
    return {
        "id": curve_id,
        "expression": expression,
        "label": label,
        "visible": visible,
        "domainMin": domain_min,
        "domainMax": domain_max,
        "leftOpen": left_open,
        "rightOpen": right_open,
    }


def _scene(
    curves: list[dict],
    *,
    mode: str = "graph",
    x_min: float = -3,
    x_max: float = 3,
    y_min: float = -2,
    y_max: float = 6,
    x0: float = 0.6,
    epsilon: float = 0.3,
    delta: float = 0.2,
    h: float = 0.25,
    integral_start: float = 0,
    integral_end: float = 1,
    subdivisions: int = 20,
    order: int = 3,
    parameters: list[dict] | None = None,
) -> dict:
    return {
        "curves": curves,
        "activeId": curves[0]["id"],
        "parameters": parameters or [],
        "mode": mode,
        "xMin": x_min,
        "xMax": x_max,
        "yMin": y_min,
        "yMax": y_max,
        "x0": x0,
        "epsilon": epsilon,
        "delta": delta,
        "h": h,
        "integralStart": integral_start,
        "integralEnd": integral_end,
        "subdivisions": subdivisions,
        "order": order,
    }


